import { tmpdir } from "node:os";
import { join } from "node:path";
import { demoLinks, expect, lastPart, test } from "./fixtures";
import { openOwnerRoom } from "./room-session";
import AxeBuilder from "@axe-core/playwright";

test("owner saves identity and resumes the location step", async ({ page, request, context }) => {
  const links = await demoLinks(request);
  await openOwnerRoom(page, request, lastPart(links.restaurant_booking));
  await page.goto("/owner/new");
  await page.getByLabel("Restaurant name", { exact: true }).fill("Café da Testagem");
  await page.getByLabel("Portuguese", { exact: true }).check();
  await page.getByLabel("Price range", { exact: true }).selectOption("2");
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Location", exact: true })).toBeVisible();
  const setup = page.url();
  await page.locator(".owner-location-map").click({ position: { x: 150, y: 150 } });
  await expect(page.getByLabel("Latitude", { exact: true })).not.toHaveValue("");
  await expect(page.locator(".owner-map-pin")).toBeVisible();
  const beforeDrag = await page.getByLabel("Latitude", { exact: true }).inputValue();
  const pin = (await page.locator(".owner-map-pin").boundingBox())!;
  await page.mouse.move(pin.x + pin.width / 2, pin.y + pin.height / 2);
  await page.mouse.down();
  await page.mouse.move(pin.x + pin.width / 2 + 40, pin.y + pin.height / 2 + 30, { steps: 5 });
  await page.mouse.up();
  await expect(page.getByLabel("Latitude", { exact: true })).not.toHaveValue(beforeDrag);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Location", exact: true })).toBeVisible();
  await context.grantPermissions(["geolocation"]);
  await context.setGeolocation({ latitude: 38.71, longitude: -9.12 });
  await page.getByRole("button", { name: "Use my current location", exact: true }).click();
  await expect(page.getByLabel("Latitude", { exact: true })).toHaveValue("38.710000");
  await page.getByLabel("Address", { exact: true }).fill("Rua do Sol, Lisboa");
  await page.getByLabel("Latitude", { exact: true }).fill("38.7223");
  await page.getByLabel("Longitude", { exact: true }).fill("-9.1393");
  await page.getByRole("button", { name: "Save and continue", exact: true }).click();
  await expect(page.getByText("Location saved", { exact: true })).toBeVisible();
  await page.goto(setup);
  await expect(page.getByLabel("Latitude", { exact: true })).toHaveValue("38.7223");
  await page.screenshot({ path: join(tmpdir(), "seatplan-owner-location-1440.png"), fullPage: true });
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(tmpdir(), "seatplan-owner-location-390.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(setup.replace("/setup", "/profile"));
  await expect(page.getByLabel("Restaurant name", { exact: true })).toHaveValue("Café da Testagem");
  await page.getByLabel("Public link", { exact: true }).fill("cafe-da-testagem-edited");
  await page.getByRole("button", { name: "Save profile", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Profile saved" })).toBeVisible();
  await page.screenshot({ path: join(tmpdir(), "seatplan-owner-profile-1440.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(tmpdir(), "seatplan-owner-profile-390.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
