def can_write(text: str) -> bool:
    """True when every character of `text` (read as upper case) is in the font."""
    return all(character in GLYPHS for character in text.upper())


def text_width(text: str, scale: int) -> int:
    """Width in pixels of `text` written at `scale` (no trailing gap)."""
    if not text:
        return 0
    return (len(text) * ADVANCE - 1) * scale


def inked_pixels(text: str, scale: int) -> list[tuple[int, int]]:
    """Every (x, y) to colour, measured from the top-left of the text.

    Call can_write() first; an unknown character raises KeyError.
    """
    pixels = []
    for index, character in enumerate(text.upper()):
        left = index * ADVANCE * scale
        for row, bits in enumerate(GLYPHS[character]):
            for column, bit in enumerate(bits):
                if bit != "1":
                    continue
                for dy in range(scale):
                    for dx in range(scale):
                        pixels.append((left + column * scale + dx, row * scale + dy))
    return pixels
